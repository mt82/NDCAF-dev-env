#!/usr/bin/env bash
# Generates the ND_CAFMaker input FCL file from variables defined in setup-config.sh.

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOTFOLDER="$(cd "$SCRIPT_DIR/.." && pwd)"
source "$SCRIPT_DIR/setup-config.sh"

# --- GHEP ndlarfid files (RUNID_GHEP + INDEX 0-9) ---
GHEPFILE_NDLARFID_00="${PATH_GHEP}${PREFIX_GHEP_NDLARFID}${RUNID_GHEP}0${SUFFIX_GHEP}"
GHEPFILE_NDLARFID_01="${PATH_GHEP}${PREFIX_GHEP_NDLARFID}${RUNID_GHEP}1${SUFFIX_GHEP}"
GHEPFILE_NDLARFID_02="${PATH_GHEP}${PREFIX_GHEP_NDLARFID}${RUNID_GHEP}2${SUFFIX_GHEP}"
GHEPFILE_NDLARFID_03="${PATH_GHEP}${PREFIX_GHEP_NDLARFID}${RUNID_GHEP}3${SUFFIX_GHEP}"
GHEPFILE_NDLARFID_04="${PATH_GHEP}${PREFIX_GHEP_NDLARFID}${RUNID_GHEP}4${SUFFIX_GHEP}"
GHEPFILE_NDLARFID_05="${PATH_GHEP}${PREFIX_GHEP_NDLARFID}${RUNID_GHEP}5${SUFFIX_GHEP}"
GHEPFILE_NDLARFID_06="${PATH_GHEP}${PREFIX_GHEP_NDLARFID}${RUNID_GHEP}6${SUFFIX_GHEP}"
GHEPFILE_NDLARFID_07="${PATH_GHEP}${PREFIX_GHEP_NDLARFID}${RUNID_GHEP}7${SUFFIX_GHEP}"
GHEPFILE_NDLARFID_08="${PATH_GHEP}${PREFIX_GHEP_NDLARFID}${RUNID_GHEP}8${SUFFIX_GHEP}"
GHEPFILE_NDLARFID_09="${PATH_GHEP}${PREFIX_GHEP_NDLARFID}${RUNID_GHEP}9${SUFFIX_GHEP}"

# --- GHEP rockantindlarfid files (RUNID_GHEP + INDEX 0-9) ---
GHEPFILE_ROCKANT_00="${PATH_GHEP}${PREFIX_GHEP_ROCKANT}${RUNID_GHEP}0${SUFFIX_GHEP}"
GHEPFILE_ROCKANT_01="${PATH_GHEP}${PREFIX_GHEP_ROCKANT}${RUNID_GHEP}1${SUFFIX_GHEP}"
GHEPFILE_ROCKANT_02="${PATH_GHEP}${PREFIX_GHEP_ROCKANT}${RUNID_GHEP}2${SUFFIX_GHEP}"
GHEPFILE_ROCKANT_03="${PATH_GHEP}${PREFIX_GHEP_ROCKANT}${RUNID_GHEP}3${SUFFIX_GHEP}"
GHEPFILE_ROCKANT_04="${PATH_GHEP}${PREFIX_GHEP_ROCKANT}${RUNID_GHEP}4${SUFFIX_GHEP}"
GHEPFILE_ROCKANT_05="${PATH_GHEP}${PREFIX_GHEP_ROCKANT}${RUNID_GHEP}5${SUFFIX_GHEP}"
GHEPFILE_ROCKANT_06="${PATH_GHEP}${PREFIX_GHEP_ROCKANT}${RUNID_GHEP}6${SUFFIX_GHEP}"
GHEPFILE_ROCKANT_07="${PATH_GHEP}${PREFIX_GHEP_ROCKANT}${RUNID_GHEP}7${SUFFIX_GHEP}"
GHEPFILE_ROCKANT_08="${PATH_GHEP}${PREFIX_GHEP_ROCKANT}${RUNID_GHEP}8${SUFFIX_GHEP}"
GHEPFILE_ROCKANT_09="${PATH_GHEP}${PREFIX_GHEP_ROCKANT}${RUNID_GHEP}9${SUFFIX_GHEP}"

# --- Reco / sim files ---
NDLAR_RECO_FILE="${PATH_SPINE}${PREFIX_SPINE}${RUNID_SPINE}${SUFFIX_SPINE}"
TMS_RECO_FILE="${PATH_TMS}${PREFIX_TMS}${RUNID_TMS}${SUFFIX_TMS}"
EDEPSIM_FILE="${PATH_EDEPSIM}${PREFIX_EDEPSIM}${RUNID_EDEPSIM}${SUFFIX_EDEPSIM}"

cat > "$FCL_CAFMAKER_INPUT" <<EOF
#include "NDCAFMaker.fcl"

nd_cafmaker: @local::standard_nd_cafmaker

nd_cafmaker.CAFMakerSettings.GHEPFiles: [
   "$GHEPFILE_NDLARFID_00",
   "$GHEPFILE_NDLARFID_01",
   "$GHEPFILE_NDLARFID_02",
   "$GHEPFILE_NDLARFID_03",
   "$GHEPFILE_NDLARFID_04",
   "$GHEPFILE_NDLARFID_05",
   "$GHEPFILE_NDLARFID_06",
   "$GHEPFILE_NDLARFID_07",
   "$GHEPFILE_NDLARFID_08",
   "$GHEPFILE_NDLARFID_09",

   "$GHEPFILE_ROCKANT_00",
   "$GHEPFILE_ROCKANT_01",
   "$GHEPFILE_ROCKANT_02",
   "$GHEPFILE_ROCKANT_03",
   "$GHEPFILE_ROCKANT_04",
   "$GHEPFILE_ROCKANT_05",
   "$GHEPFILE_ROCKANT_06",
   "$GHEPFILE_ROCKANT_07",
   "$GHEPFILE_ROCKANT_08",
   "$GHEPFILE_ROCKANT_09"
]

nd_cafmaker.CAFMakerSettings.OutputFile: "$OUTPUT_CAF"
nd_cafmaker.CAFMakerSettings.NDLArRecoFile: "$NDLAR_RECO_FILE"
nd_cafmaker.CAFMakerSettings.TMSRecoFile: "$TMS_RECO_FILE"
nd_cafmaker.CAFMakerSettings.EdepsimFile: "$EDEPSIM_FILE"
EOF

echo "Written: $FCL_CAFMAKER_INPUT"
